import { TrendingUp, TrendingDown, RefreshCw } from 'lucide-react';
import './PredictionResult.css';

/**
 * Determine UI risk level from churn_percentage (not multiplied again).
 * 0–39.9  → Low
 * 40–69.9 → Moderate
 * 70–100  → High
 */
function getRiskLevel(pct) {
  if (pct < 40) return { label: 'Low Churn Risk',      color: 'success', className: 'risk-low' };
  if (pct < 70) return { label: 'Moderate Churn Risk', color: 'warning', className: 'risk-moderate' };
  return              { label: 'High Churn Risk',       color: 'danger',  className: 'risk-high' };
}

export default function PredictionResult({ result, onReset }) {
  if (!result) return null;

  const { prediction_label, churn_percentage } = result;
  const isChurn = prediction_label === 'Churn';
  const risk = getRiskLevel(churn_percentage);

  const interpretation = isChurn
    ? 'The model identified this customer as having an elevated likelihood of churn based on the provided information.'
    : 'The model currently predicts that this customer is more likely to remain with the service.';

  return (
    <section id="prediction-result" className="result-section" aria-labelledby="result-heading">
      <div className="container">
        <div className={`card result-card ${isChurn ? 'result-churn' : 'result-no-churn'}`}>

          {/* Header */}
          <div className="result-header">
            <div className="result-header-icon">
              {isChurn ? <TrendingDown size={22} /> : <TrendingUp size={22} />}
            </div>
            <div>
              <h2 id="result-heading" className="result-title">Churn Risk Analysis</h2>
              <p className="result-subtitle">Model prediction results</p>
            </div>
          </div>

          <div className="divider" />

          {/* Main result */}
          <div className="result-main">
            {/* Prediction label */}
            <div className="result-item">
              <span className="result-item-label">Prediction</span>
              <span className={`result-prediction-badge badge ${isChurn ? 'badge-danger' : 'badge-success'}`}>
                {prediction_label}
              </span>
            </div>

            {/* Risk level (UI only) */}
            <div className="result-item">
              <span className="result-item-label">Risk Level</span>
              <span className={`badge ${risk.className === 'risk-low' ? 'badge-success' : risk.className === 'risk-moderate' ? 'badge-warning' : 'badge-danger'}`}>
                {risk.label}
              </span>
            </div>
          </div>

          {/* Probability gauge */}
          <div className="result-gauge-section">
            <div className="result-gauge-header">
              <span className="result-gauge-label">Churn Probability</span>
              <span className="result-gauge-value">{churn_percentage.toFixed(1)}%</span>
            </div>
            <div className="result-gauge-track" role="progressbar" aria-valuenow={churn_percentage} aria-valuemin="0" aria-valuemax="100" aria-label={`Churn probability: ${churn_percentage.toFixed(1)}%`}>
              <div
                className={`result-gauge-fill ${risk.className}`}
                style={{ width: `${Math.min(churn_percentage, 100)}%` }}
              />
              {/* Threshold markers */}
              <div className="gauge-marker" style={{ left: '40%' }} title="Low / Moderate threshold" />
              <div className="gauge-marker" style={{ left: '70%' }} title="Moderate / High threshold" />
            </div>
            <div className="gauge-legend">
              <span className="gauge-legend-item success">0–39% Low</span>
              <span className="gauge-legend-item warning">40–69% Moderate</span>
              <span className="gauge-legend-item danger">70–100% High</span>
            </div>
          </div>

          <div className="divider" />

          {/* Interpretation */}
          <p className="result-interpretation">{interpretation}</p>

          {/* Disclaimer */}
          <p className="result-disclaimer">
            This prediction is generated by a machine learning model and should be considered as one factor in decision-making, not as a definitive conclusion.
          </p>

          {/* Reset button */}
          <div className="result-actions">
            <button
              id="analyze-another-btn"
              className="btn btn-outline"
              onClick={onReset}
            >
              <RefreshCw size={15} />
              Analyze Another Customer
            </button>
          </div>

        </div>
      </div>
    </section>
  );
}
